-- =============================================================================
-- SQL DATASET SETUP
-- Database: PostgreSQL 17+
--
-- Purpose:
--   Create a small, realistic e-commerce schema for SQL demonstrations.
--   The schema is normalized into customers, products, orders, order_items,
--   and payments. The sample data deliberately includes common real-world
--   cases: customers with no orders, products never ordered, cancelled orders,
--   failed/pending/refunded payments, NULL values, repeat customers, and
--   orders containing multiple items.
--
-- IMPORTANT:
--   This is a RESET script for a dedicated tutorial database.
--   It drops these five tables if they already exist, then recreates them.
--   Do not run it against a database containing data you need to keep.
-- =============================================================================

BEGIN;

-- Drop in child-to-parent order so foreign-key dependencies are respected.
DROP TABLE IF EXISTS payments;
DROP TABLE IF EXISTS order_items;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS products;
DROP TABLE IF EXISTS customers;

-- =============================================================================
-- 1. CUSTOMERS
-- One row per registered customer.
-- =============================================================================

CREATE TABLE customers (
    customer_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name       VARCHAR(80) NOT NULL,
    last_name        VARCHAR(80) NOT NULL,
    email            VARCHAR(255) NOT NULL UNIQUE,
    phone            VARCHAR(30),
    city             VARCHAR(100),
    state            VARCHAR(100),
    country_code     CHAR(2) NOT NULL DEFAULT 'IN',
    customer_segment VARCHAR(20) NOT NULL DEFAULT 'standard'
                     CHECK (customer_segment IN ('standard', 'silver', 'gold', 'platinum')),
    signup_date      DATE NOT NULL,
    is_active        BOOLEAN NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =============================================================================
-- 2. PRODUCTS
-- One row per product currently listed in the catalog.
-- =============================================================================

CREATE TABLE products (
    product_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku             VARCHAR(40) NOT NULL UNIQUE,
    product_name    VARCHAR(200) NOT NULL,
    category        VARCHAR(80) NOT NULL,
    unit_price      NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0),
    cost_price      NUMERIC(10, 2) CHECK (cost_price IS NULL OR cost_price >= 0),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    launched_at     DATE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =============================================================================
-- 3. ORDERS
-- One row per order. customer_id links an order to its customer.
-- Order totals are calculated from order_items during analytics rather than
-- stored here, avoiding duplicated and potentially inconsistent data.
-- =============================================================================

CREATE TABLE orders (
    order_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     BIGINT NOT NULL REFERENCES customers(customer_id),
    order_date      TIMESTAMPTZ NOT NULL,
    order_status    VARCHAR(20) NOT NULL
                    CHECK (order_status IN (
                        'pending', 'confirmed', 'processing', 'shipped',
                        'delivered', 'cancelled', 'returned'
                    )),
    sales_channel   VARCHAR(20) NOT NULL
                    CHECK (sales_channel IN ('website', 'mobile_app', 'marketplace', 'store')),
    shipping_city   VARCHAR(100),
    shipping_state  VARCHAR(100),
    coupon_code     VARCHAR(40),
    notes           TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =============================================================================
-- 4. ORDER ITEMS
-- One row per product line within an order.
-- unit_price is a snapshot of the price at purchase time. It intentionally
-- does not change when the current products.unit_price changes.
-- =============================================================================

CREATE TABLE order_items (
    order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    product_id    BIGINT NOT NULL REFERENCES products(product_id),
    quantity      INTEGER NOT NULL CHECK (quantity > 0),
    unit_price    NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0),
    discount_amount NUMERIC(10, 2) NOT NULL DEFAULT 0
                    CHECK (discount_amount >= 0),
    UNIQUE (order_id, product_id),
    CHECK (discount_amount <= quantity * unit_price)
);

-- =============================================================================
-- 5. PAYMENTS
-- One order can have more than one payment attempt.
-- A failed attempt can be followed by a successful attempt.
-- =============================================================================

CREATE TABLE payments (
    payment_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT NOT NULL REFERENCES orders(order_id),
    payment_date    TIMESTAMPTZ,
    amount          NUMERIC(12, 2) NOT NULL CHECK (amount >= 0),
    payment_method  VARCHAR(20) NOT NULL
                    CHECK (payment_method IN ('upi', 'card', 'net_banking', 'wallet', 'cod')),
    payment_status  VARCHAR(20) NOT NULL
                    CHECK (payment_status IN (
                        'initiated', 'pending', 'succeeded', 'failed',
                        'refunded', 'partially_refunded'
                    )),
    transaction_ref VARCHAR(100) UNIQUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =============================================================================
-- INDEXES
-- Primary keys and UNIQUE constraints already create indexes. These additional
-- indexes support common joins and date/status filters used in the tutorial.
-- =============================================================================

CREATE INDEX idx_orders_customer_id ON orders(customer_id);
CREATE INDEX idx_orders_order_date ON orders(order_date);
CREATE INDEX idx_orders_status_date ON orders(order_status, order_date);
CREATE INDEX idx_order_items_product_id ON order_items(product_id);
CREATE INDEX idx_payments_order_id ON payments(order_id);
CREATE INDEX idx_payments_status ON payments(payment_status);

